const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..'),SOURCE_DIRECTORY=path.join(ROOT,'assets/motifs'),OUTPUT_PATH=path.join(ROOT,'js/motif-textures.js');
const textures=Object.fromEntries(fs.readdirSync(SOURCE_DIRECTORY).filter(name=>name.endsWith('.svg')).sort().map(name=>[
  path.basename(name,'.svg'),'data:image/svg+xml;base64,'+fs.readFileSync(path.join(SOURCE_DIRECTORY,name)).toString('base64'),
]));
fs.writeFileSync(OUTPUT_PATH,'// Generated by tools/build-motif-textures.cjs from assets/motifs/*.svg.\n'+
  '// Embedded images keep WebGL textures available on file:// as well as HTTP.\n'+
  'window.Starhound.MotifTextures=Object.freeze('+JSON.stringify(textures,null,2)+');\n');
